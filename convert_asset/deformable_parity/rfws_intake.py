def _sha256_file(path: Path) -> str:
    h = sha256()
    with path.open("rb") as f:
        while chunk := f.read(1024 * 1024):
            h.update(chunk)
    return h.hexdigest()


def _write_obj(path: Path, vertices: np.ndarray, faces: np.ndarray) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by convert_asset.deformable_parity.rfws_intake"]
    for v in vertices:
        lines.append(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}")
    for f in faces:
        lines.append(f"f {int(f[0]) + 1} {int(f[1]) + 1} {int(f[2]) + 1}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def build_subdivided_box_mesh(
    size_xyz_m: tuple[float, float, float],
    subdiv_xyz: tuple[int, int, int] = (4, 4, 2),
) -> tuple[np.ndarray, np.ndarray]:
    """Build a watertight triangulated surface mesh of a centered box."""
    sx, sy, sz = size_xyz_m
    nx, ny, nz = subdiv_xyz
    hx, hy, hz = 0.5 * sx, 0.5 * sy, 0.5 * sz

    verts: list[tuple[float, float, float]] = []
    vert_map: dict[tuple[int, int, int], int] = {}

    def get_vid(ix: int, iy: int, iz: int) -> int:
        key = (ix, iy, iz)
        if key not in vert_map:
            vert_map[key] = len(verts)
            verts.append(
                (
                    -hx + (sx * ix) / nx,
                    -hy + (sy * iy) / ny,
                    -hz + (sz * iz) / nz,
                )
            )
        return vert_map[key]

    faces: list[tuple[int, int, int]] = []

    def add_quad(v00: int, v10: int, v11: int, v01: int, flip: bool) -> None:
        if not flip:
            faces.append((v00, v10, v11))
            faces.append((v00, v11, v01))
        else:
            faces.append((v00, v11, v10))
            faces.append((v00, v01, v11))

    # Top (+Z) and Bottom (-Z)
    for iz, flip in ((nz, False), (0, True)):
        for ix in range(nx):
            for iy in range(ny):
                add_quad(
                    get_vid(ix, iy, iz),
                    get_vid(ix + 1, iy, iz),
                    get_vid(ix + 1, iy + 1, iz),
                    get_vid(ix, iy + 1, iz),
                    flip=flip,
                )

    # Front (-Y) and Back (+Y)
    for iy, flip in ((0, False), (ny, True)):
        for ix in range(nx):
            for iz in range(nz):
                add_quad(
                    get_vid(ix, iy, iz),
                    get_vid(ix + 1, iy, iz),
                    get_vid(ix + 1, iy, iz + 1),
                    get_vid(ix, iy, iz + 1),
                    flip=flip,
                )

    # Left (-X) and Right (+X)
    for ix, flip in ((0, True), (nx, False)):
        for iy in range(ny):
            for iz in range(nz):
                add_quad(
                    get_vid(ix, iy, iz),
                    get_vid(ix, iy + 1, iz),
                    get_vid(ix, iy + 1, iz + 1),
                    get_vid(ix, iy, iz + 1),
                    flip=flip,
                )

    return np.asarray(verts, dtype=np.float64), np.asarray(faces, dtype=np.int32)


def build_grid_cloth_mesh(
    width_m: float,
    length_m: float,
    grid_xy: tuple[int, int] = (12, 12),
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Build a centered flat triangulated cloth grid mesh and its structural edges."""
    nx, ny = grid_xy
    verts = np.zeros(((ny + 1) * (nx + 1), 3), dtype=np.float64)
    for iy in range(ny + 1):
        for ix in range(nx + 1):
            idx = iy * (nx + 1) + ix
            verts[idx, 0] = -0.5 * width_m + (width_m * ix) / nx
            verts[idx, 1] = -0.5 * length_m + (length_m * iy) / ny
            verts[idx, 2] = 0.0

    faces: list[tuple[int, int, int]] = []
    edges_set: set[tuple[int, int]] = set()
    for iy in range(ny):
        for ix in range(nx):
            v0 = iy * (nx + 1) + ix
            v1 = v0 + 1
            v2 = (iy + 1) * (nx + 1) + ix
            v3 = v2 + 1
            if (ix % 2 == 0) != (iy % 2 == 0):
                tris = [(v0, v1, v2), (v1, v3, v2)]
            else:
                tris = [(v0, v1, v3), (v0, v3, v2)]
            for a, b, c in tris:
                faces.append((a, b, c))
                for u, w in ((a, b), (b, c), (c, a)):
                    edges_set.add((min(u, w), max(u, w)))

    edges = np.asarray(sorted(edges_set), dtype=np.int32)
    return verts, np.asarray(faces, dtype=np.int32), edges


def build_pilot_fragile_chocopie_tofu_spec(asset_root: Path) -> DeformableSourceSpec:
    """Create Pilot Asset 1: fragile elastoplastic soft solid (70 x 70 x 28 mm)."""
    dims = (0.070, 0.070, 0.028)
    verts, faces = build_subdivided_box_mesh(dims, subdiv_xyz=(4, 4, 2))
    visual_rel = "source/visual_mesh.obj"
    proxy_rel = "source/proxy_mesh.obj"
    visual_path = asset_root / visual_rel
    proxy_path = asset_root / proxy_rel
    _write_obj(visual_path, verts, faces)
    _write_obj(proxy_path, verts, faces)

    density = 950.0
    mass = dims[0] * dims[1] * dims[2] * density
    return DeformableSourceSpec(
        asset_id="pilot_fragile_chocopie_tofu_01",
        category="fragile_soft_solid",
        structural_family="soft_solid",
        dimensions_xyz_m=dims,
        mass_kg=float(round(mass, 6)),
        density_kg_m3=density,
        youngs_modulus_pa=28000.0,
        poissons_ratio=0.32,
        yield_stress_pa=5000.0,
        plastic_strain_band=(0.15, 0.45),
        visual_mesh_relpath=visual_rel,
        proxy_mesh_relpath=proxy_rel,
        mesh_topology={
            "kind": "box_surface_tet_candidate",
            "subdiv_xyz": [4, 4, 2],
            "num_vertices": int(len(verts)),
            "num_triangles": int(len(faces)),
        },
        fragility_tier="high",
        source_dataset="self_authored_pilot",
        source_asset_sha256=_sha256_file(visual_path),
    )


