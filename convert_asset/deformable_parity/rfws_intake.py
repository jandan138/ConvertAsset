def load_rfws_asset_record(asset_dir: Path) -> DeformableSourceSpec:
    """Parse an external RFW-S asset record directory into DeformableSourceSpec."""
    meta_path = None
    for cand in ("manifest.json", "meta.json", "asset.json"):
        p = asset_dir / cand
        if p.is_file():
            meta_path = p
            break
    if meta_path is None:
        raise FileNotFoundError(
            f"No RFW-S metadata file (manifest.json/meta.json/asset.json) found in {asset_dir}"
        )
    data: dict[str, Any] = json.loads(meta_path.read_text(encoding="utf-8"))
    visual_rel = str(data.get("visual_mesh_relpath") or data.get("visual_mesh") or "")
    proxy_rel = str(data.get("proxy_mesh_relpath") or data.get("physical_proxy") or visual_rel)
    if not visual_rel or not (asset_dir / visual_rel).is_file():
        raise FileNotFoundError(f"RFW-S visual mesh missing: {asset_dir / visual_rel}")

    dims_raw = data.get("dimensions_xyz_m") or [0.10, 0.10, 0.05]
    band_raw = data.get("plastic_strain_band")
    return DeformableSourceSpec(
        asset_id=str(data.get("asset_id") or asset_dir.name),
        category=str(data.get("category") or "unknown"),
        structural_family=str(data.get("structural_family") or "soft_solid"),
        dimensions_xyz_m=(float(dims_raw[0]), float(dims_raw[1]), float(dims_raw[2])),
        mass_kg=float(data.get("mass_kg", 0.15)),
        density_kg_m3=float(data.get("density_kg_m3", 800.0)),
        youngs_modulus_pa=float(data.get("youngs_modulus_pa", 5.0e4)),
        poissons_ratio=float(data.get("poissons_ratio", 0.35)),
        yield_stress_pa=(
            float(data["yield_stress_pa"]) if data.get("yield_stress_pa") is not None else None
        ),
        plastic_strain_band=(
            (float(band_raw[0]), float(band_raw[1])) if band_raw is not None else None
        ),
        visual_mesh_relpath=visual_rel,
        proxy_mesh_relpath=proxy_rel,
        mesh_topology=dict(data.get("mesh_topology", {})),
        fragility_tier=str(data.get("fragility_tier", "medium")),
        source_dataset="RFW-S",
        source_asset_sha256=_sha256_file(asset_dir / visual_rel),
    )

