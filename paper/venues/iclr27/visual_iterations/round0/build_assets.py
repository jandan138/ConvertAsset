#!/usr/bin/env python3
"""Generate ICLR figures/tables from corrected JSON analysis; no hand-entered scores."""
from __future__ import annotations
import argparse
import csv
import hashlib
import json
from pathlib import Path

import numpy as np

VENUE = Path(__file__).resolve().parents[1]
ROOT = VENUE.parents[2]
SOURCE = ROOT / "paper/shared/evidence/raw/iclr_model_behavior/analysis_v1/results.json"
MODEL_ORDER = ["Gemma4-E4B", "Qwen2.5-VL-7B", "Qwen3-VL-2B", "Qwen3-VL-8B", "InternVL3-8B", "Molmo-7B-D"]
FIGURE_NAMES = ("overview", "grounding", "protocol", "interventions", "navigation", "trajectories")
FIGURE_FORMATS = ("svg", "pdf", "png")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def pct(x):
    return f"{100*x:.1f}"


def tex_table(name, columns, header, rows):
    lines = ["% Generated by scripts/build_assets.py from corrected results.json", "\\begin{tabular}{" + columns + "}",
             "\\toprule", " & ".join(header) + r" \\", "\\midrule"]
    lines += [r"\midrule" if row is None else " & ".join(map(str, row)) + r" \\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    (VENUE / "tables" / f"{name}.tex").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=SOURCE)
    args = parser.parse_args()
    data = json.loads(args.results.read_text())
    for sub in ("tables", "figures"):
        (VENUE / sub).mkdir(exist_ok=True)
    runs = data["runs"]
    canon = {r["model"]: r for r in runs if r["pool"] == "extended80" and r["prompt"] == "s1_point"}
    rows = []
    for model in MODEL_ORDER:
        run = canon[model]
        s = run["score"]
        z = run["current_stress30_slice"]
        rows.append([model, pct(z["original"]["success_rate"]), pct(z["converted"]["success_rate"]),
                     pct(s["original"]["success_rate"]), pct(s["converted"]["success_rate"]),
                     f"{100*s['delta']:+.1f}", f"{s['flip_n']}/{s['n_pairs']}"])
    tex_table("grounding", "lrrrrrr", ["Model", "\\multicolumn{2}{c}{Close views (30)}", "\\multicolumn{2}{c}{Mixed views (80)}", "$\\Delta$ (pp)", "Flips"], rows)

    # Requested-frame protocol matrix: no post-hoc frame selection.
    protocols = [("normalized_1000", "structured_text"), ("normalized_1000", "json"),
                 ("pixel", "structured_text"), ("pixel", "json")]
    matrix = np.full((6, 4), np.nan)
    coverage = []
    for i, model in enumerate(MODEL_ORDER):
        for j, (frame, fmt) in enumerate(protocols):
            matches = [r for r in runs if r["model"] == model and r["pool"] == "stress30" and r["prompt"] == "s1_point"
                       and r["frame"] == frame and r["format"] == fmt]
            if j == 0:
                s = canon[model]["current_stress30_slice"]
            else:
                s = matches[0]["score"]
            matrix[i, j] = 100 * s["delta"]
            coverage.append([model, frame.replace("normalized_1000", "0--1000"), "text" if fmt == "structured_text" else "JSON",
                             f"{s['original']['valid_point_n']}/{s['n_pairs']}", f"{s['converted']['valid_point_n']}/{s['n_pairs']}",
                             pct(s["original"]["success_rate"]), pct(s["converted"]["success_rate"])])
    tex_table("protocol_full", "lllrrrr", ["Model", "Frame", "Format", "$V_O$", "$V_C$", "$H_O$ (\\%)", "$H_C$ (\\%)"], coverage)
    # New image-composition mechanisms.
    new = [r for r in runs if r["pool"] in {"two_view_category", "two_view_action", "target_window", "context_window"}]
    families = ("two_view_category", "two_view_action", "target_window", "context_window")
    new.sort(key=lambda r: (MODEL_ORDER.index(r["model"]), families.index(r["pool"])))
    rows = []
    previous_model = None
    family_labels = {"two_view_category": "Category query", "two_view_action": "Action query",
                     "target_window": "Target window", "context_window": "Context window"}
    for r in new:
        if previous_model is not None and previous_model != r["model"]:
            rows.append(None)
        model_label = r["model"] if r["model"] != previous_model else ""
        previous_model = r["model"]
        s = r["score"]
        rows.append([model_label, family_labels[r["pool"]], s["n_pairs"], pct(s["original"]["success_rate"]),
                     pct(s["converted"]["success_rate"]), f"{100*s['delta']:+.1f}", f"{s['flip_n']}/{s['n_pairs']}"])
    tex_table("interventions", "llrrrrr", ["Model", "Intervention", "$N$", "Original", "Changed", "$\\Delta$ (pp)", "Flips"], rows)
    tex_table("sampling", "lrrr", ["Model", "Complete triples", "Seed distance (px)", "Hit variability (\\%)"],
              [[s["model"], f"{s['complete_point_queries']}/{s['queries']}",
                f"{s['mean_pairwise_seed_distance_px']:.2f}", pct(s["hit_instability"])] for s in data["sampling"]])
    # Navigation: preserve downstream results and reveal cancellations.
    nav = data["navigation"]
    transitions = np.zeros((2, 2), dtype=int)
    csv_path = ROOT / "paper/shared/evidence/raw/internnav_vln_downstream/official_val_unseen_99/paired_episode_transitions.csv"
    episodes = list(csv.DictReader(csv_path.open()))
    scene_rows = []
    for row in episodes:
        transitions[int(float(row["original_SR"]))][int(float(row["nomdl_SR"]))] += 1
    for scene in sorted({r["scene_id"] for r in episodes}):
        rs = [r for r in episodes if r["scene_id"] == scene]
        scene_rows.append([scene.replace("kujiale_", ""), len(rs),
                           *[f"{100*sum(float(r[k]) for r in rs)/len(rs):.1f}" for k in ("original_SR", "nomdl_SR", "original_SPL", "nomdl_SPL")],
                           sum(r["original_SR"] != r["nomdl_SR"] for r in rs)])
    scene_rows.append(None)
    scene_rows.append(["All", nav["n"], *[pct(nav["metrics"][m][c]) for m in ("SR", "SPL") for c in ("original_mean", "modified_mean")], nav["flips"]])
    tex_table("navigation", "lrrrrrr", ["Scene", "$N$", "$SR_O$", "$SR_C$", "$SPL_O$", "$SPL_C$", "Flips"], scene_rows)
    from figure_style import render_all
    image_sources = render_all(data)
    for name in FIGURE_NAMES:
        for suffix in FIGURE_FORMATS:
            if not (VENUE / "figures" / f"{name}.{suffix}").is_file():
                raise ValueError(f"Missing generated figure: {name}.{suffix}")
    mf = ROOT / "paper/shared/evidence/raw/iclr_model_behavior/interventions_clean_v2/manifest.json"
    manifest = json.loads(mf.read_text())
    macros = {"NavN": str(nav["n"]), "NavFlips": str(nav["flips"]), "NavFlipPercent": pct(nav["flips"]/nav["n"]),
              "NavSrOriginal": pct(nav["metrics"]["SR"]["original_mean"]), "NavSrConverted": pct(nav["metrics"]["SR"]["modified_mean"]),
              "NewRunCount": str(len(new)), "BoardCount": str(manifest["n_boards"])}
    for model, prefix in (("Gemma4-E4B", "Gemma"), ("Qwen3-VL-2B", "Small"), ("Qwen3-VL-8B", "Large")):
        for family, suffix in (("two_view_category", "Full"), ("two_view_action", "Action"),
                               ("target_window", "Target"), ("context_window", "Context")):
            r = next((r for r in new if r["model"] == model and r["pool"] == family), None)
            if r:
                for condition, side in (("original", "Orig"), ("converted", "Conv")):
                    macros[prefix + suffix + side] = str(r["score"][condition]["hit_n"])
                    macros[prefix + suffix + side + "Percent"] = pct(r["score"][condition]["success_rate"])
                macros[prefix + suffix + "Flips"] = str(r["score"]["flip_n"])
    (VENUE / "tables/numbers.tex").write_text("\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k,v in macros.items()) + "\n")
    outputs = [p for d in ("tables", "figures") for p in (VENUE / d).rglob("*") if p.is_file()]
    generators = [Path(__file__), Path(__file__).with_name("figure_style.py")]
    (VENUE / "ASSET_PROVENANCE.json").write_text(json.dumps({"results": str(args.results.relative_to(ROOT)),
            "results_sha256": sha(args.results), "generator_sha256": sha(__file__),
            "generators": {str(p.relative_to(VENUE)): sha(p) for p in generators},
            "image_sources": {str(p.relative_to(ROOT)): sha(p) for p in image_sources},
            "outputs": {str(p.relative_to(VENUE)): sha(p) for p in outputs}}, indent=2) + "\n")
    print(f"Generated {len(outputs)} assets from {len(runs)} result rows")


if __name__ == "__main__":
    main()
